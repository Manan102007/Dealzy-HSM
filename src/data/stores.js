export function getStoreById(storeId) {
    return STORES_DATA.find((s) => s.id === storeId) || null;
}

export function getProductById(storeId, productId) {
    const store = getStoreById(storeId);
    if (!store || !store.products) return null;
    return store.products.find((p) => p.id === productId) || null;
}
